// IDs are stable: neither question order nor option order identifies the answer.
function question(
  id: string,
  category: string,
  text: string,
  options: Record<string, string>,
  correctOptionId: string,
  explanation: string,
): Question {
  return {
    id,
    category,
    question: text,
    options: Object.entries(options).map(([id, text]) => ({ id, text })),
    correctOptionId,
    explanation,
  };
}

